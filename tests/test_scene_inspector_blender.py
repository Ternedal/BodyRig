@pytest.mark.skipif(not REQUIRE_BWRAP, reason="bubblewrap isolation is only required on the Linux CI job")
def test_bwrap_hides_home_and_network(tmp_path) -> None:
    assert si.bwrap_available()
    secret = Path.home() / f".bodyrig-bwrap-probe-{os.getpid()}"
    secret.write_text("secret")
    try:
        job = tmp_path / "job"
        job.mkdir()
        code = ("import os, socket, sys\n"
                f"assert not os.path.exists({str(secret)!r}), 'home visible'\n"
                "try:\n    socket.create_connection(('1.1.1.1', 53), timeout=3)\n    sys.exit(5)\n"
                "except OSError:\n    pass\n"
                "open('ok.txt', 'w').write('ok')\n")
        python = Path(os.path.abspath(sys.executable))
        read_only = si.BlenderRuntime("module", python, "probe").read_only_paths()
        argv = si.bwrap_prefix(job, read_only, si.child_env(job)) + [str(python), "-I", "-c", code]
        subprocess.run(argv, check=True, timeout=60)
        assert (job / "ok.txt").read_text() == "ok"
    finally:
        secret.unlink()


