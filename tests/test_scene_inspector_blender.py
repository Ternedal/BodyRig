"""End-to-end scene inspection with a real, pinned Blender.

Skipped unless a runtime is configured:

- ``BODYRIG_BPY_PYTHON``: a Python 3.11 with requirements/blender-bpy.lock.txt installed, or
- ``BODYRIG_BLENDER``: a blender executable.

``BODYRIG_REQUIRE_BWRAP=1`` additionally requires bubblewrap isolation (Linux CI).
The corpus is generated by Blender itself (tests/blender_fixtures/make_scene_corpus_bpy.py).
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from bodyrig import scene_inspector as si

BPY_PYTHON = os.environ.get("BODYRIG_BPY_PYTHON")
BLENDER = os.environ.get("BODYRIG_BLENDER")
REQUIRE_BWRAP = os.environ.get("BODYRIG_REQUIRE_BWRAP") == "1"
CORPUS_SCRIPT = Path(__file__).parent / "blender_fixtures" / "make_scene_corpus_bpy.py"
SAMPLES = ("sample.blend", "sample.fbx", "sample.glb", "sample.gltf", "sample.obj")

pytestmark = pytest.mark.skipif(not (BPY_PYTHON or BLENDER), reason="no pinned Blender/bpy runtime configured")


@pytest.fixture(scope="module")
def runtime(tmp_path_factory) -> si.BlenderRuntime:
    cache = tmp_path_factory.mktemp("runtime")
    if BPY_PYTHON:
        return si.detect_runtime(bpy_python=Path(BPY_PYTHON), cache_root=cache)
    return si.detect_runtime(blender=Path(BLENDER), cache_root=cache)


@pytest.fixture(scope="module")
def corpus(tmp_path_factory, runtime) -> Path:
    out = tmp_path_factory.mktemp("corpus")
    if runtime.kind == "module":
        argv = [str(runtime.executable), "-I", str(CORPUS_SCRIPT), "--", str(out)]
    else:
        argv = [str(runtime.executable), "--background", "--factory-startup", "--python", str(CORPUS_SCRIPT),
                "--", str(out)]
    subprocess.run(argv, check=True, timeout=300, capture_output=True)
    return out


def _options(**kw) -> si.InspectOptions:
    base = {"conditioning": ("pose", "depth", "normal"), "resolution": 128, "wall_seconds": 240.0,
            "isolation": "bwrap" if REQUIRE_BWRAP else "none"}
    base.update(kw)
    return si.InspectOptions(**base).validate()


@pytest.fixture(scope="module")
def first_pass(tmp_path_factory, runtime, corpus):
    cache = si.SceneCache(tmp_path_factory.mktemp("cache"))
    out = tmp_path_factory.mktemp("out")
    summary = si.inspect_batch(corpus, list(SAMPLES) + ["autorun.blend", "outside-texture.fbx"], out,
                               runtime=runtime, cache=cache,
                               options=_options(), jobs=2, work_root=tmp_path_factory.mktemp("work"))
    return summary, out, cache


def _scene(out: Path, summary: dict, path: str) -> dict:
    entry = next(a for a in summary["assets"] if a["path"] == path)
    return json.loads((out / entry["out"] / "scene.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("sample", SAMPLES)
def test_structure_is_reported_for_every_format(first_pass, sample: str) -> None:
    summary, out, _ = first_pass
    result = _scene(out, summary, sample)
    assert result["state"] == "FULLY_ANALYZED", result["error"]
    totals = result["scene"]["totals"]
    assert totals["meshes"] >= 1 and totals["triangles"] >= 100
    if sample == "sample.obj":
        assert totals["bones"] == 0  # OBJ carries no rig, shape keys or animation
    else:
        names = {b["name"] for a in result["scene"]["armatures"] for b in a["bones"]}
        assert {"root", "spine", "head"} <= names
        assert totals["shape_keys"] == 2 and totals["actions"] >= 1
    assert result["likeness_authority"] is False
    assert result["isolation"]["mode"] == ("bwrap" if REQUIRE_BWRAP else "process-only")
    assert result["cleanup"] == {"staging_removed": True}
    assert result["timings_ms"]["minimum_ready_at"] < 5000
    for name in ("pose.json", "pose.png", "depth.png", "normal.png"):
        produced = out / next(a["out"] for a in summary["assets"] if a["path"] == sample) / name
        assert produced.is_file() and produced.stat().st_size > 0
        assert result["conditioning"]["files"][name]
    depth = (out / next(a["out"] for a in summary["assets"] if a["path"] == sample) / "depth.png").read_bytes()
    assert depth[:8] == b"\x89PNG\r\n\x1a\n" and depth[24] == 16  # 16-bit samples
    assert result["conditioning"]["outputs"]["depth_normal"]["hit_pixels"] > 0


def test_embedded_scripts_in_a_blend_do_not_run(first_pass, corpus) -> None:
    summary, out, _ = first_pass
    result = _scene(out, summary, "autorun.blend")
    assert result["state"] == "FULLY_ANALYZED", result["error"]
    assert not (corpus / "autorun-marker.txt").exists()
    risk = result["scene"]["risk"]
    assert risk["embedded_texts"] == 1 and risk["scripted_drivers"] == 1 and risk["autoexec_blocked"] is True
    assert result["runtime"]["security"]["autoexec_enabled"] is False


def test_fbx_texture_with_an_absolute_outside_path_is_never_opened(first_pass) -> None:
    summary, out, _ = first_pass
    result = _scene(out, summary, "outside-texture.fbx")
    assert result["state"] == "FULLY_ANALYZED", result["error"]
    assert result["scene"]["risk"]["images_outside_staging"] == 0
    assert all(image.get("file_in_staging", True) for image in result["scene"]["images"])
    assert result["runtime"]["importer"]["images"]["redirected"] >= 1


GUARD_PROBE = r"""
import importlib.util, json, os, sys
worker_path, staging, outside = sys.argv[1:4]
spec = importlib.util.spec_from_file_location("worker", worker_path)
worker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(worker)
import bpy
from bpy_extras import image_utils
bpy.ops.wm.read_factory_settings(use_empty=True)
if os.environ.get("GUARD") == "1":
    worker._confine_fbx_images(staging)
image = image_utils.load_image(outside, dirname=staging, place_holder=True, recursive=True)
print(json.dumps({"filepath": os.path.realpath(bpy.path.abspath(image.filepath)), "size": list(image.size)}), flush=True)
worker.hard_exit(0)
"""


@pytest.mark.skipif(not BPY_PYTHON, reason="probes the bpy module directly")
@pytest.mark.parametrize("guard", ["1", "0"])
def test_fbx_image_loads_cannot_leave_staging(tmp_path, corpus, guard: str) -> None:
    staging = tmp_path / "staging"
    staging.mkdir()
    outside = corpus.parent / "outside-texture.png"  # written by the corpus script, outside any staging
    probe = tmp_path / "probe.py"
    probe.write_text(GUARD_PROBE, encoding="utf-8")
    run = subprocess.run([BPY_PYTHON, "-I", str(probe), str(si.WORKER_SCRIPT), str(staging), str(outside)],
                         capture_output=True, text=True, timeout=120, env={**os.environ, "GUARD": guard})
    loaded = json.loads(run.stdout.strip().splitlines()[-1])
    inside = Path(loaded["filepath"]).is_relative_to(staging.resolve())
    if guard == "1":
        assert inside and loaded["size"] == [0, 0]  # a placeholder; the outside file was never read
    else:  # control: without the guard Blender reads the outside file, so the test above has teeth
        assert not inside and loaded["size"] == [8, 8]


