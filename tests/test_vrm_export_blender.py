"""End-to-end VRM export with a real, pinned Blender and the pinned add-ons.

Skipped unless both are configured:

- ``BODYRIG_BPY_PYTHON`` (Python 3.11 with requirements/blender-bpy.lock.txt) or ``BODYRIG_BLENDER``;
- ``BODYRIG_VRM_ADDONS``: a folder made by ``scripts/vrm_export_setup.py``.

``BODYRIG_REQUIRE_BWRAP=1`` additionally requires bubblewrap isolation (Linux CI).
The corpus is abstract capsule figures generated by Blender itself
(tests/blender_fixtures/make_vrm_corpus_bpy.py); no third-party models.
"""

from __future__ import annotations

import json
import os
import struct
import subprocess
from pathlib import Path

import pytest

from bodyrig import scene_inspector as si
from bodyrig import vrm_export as ve

BPY_PYTHON = os.environ.get("BODYRIG_BPY_PYTHON")
BLENDER = os.environ.get("BODYRIG_BLENDER")
ADDONS = os.environ.get("BODYRIG_VRM_ADDONS")
REQUIRE_BWRAP = os.environ.get("BODYRIG_REQUIRE_BWRAP") == "1"
CORPUS_SCRIPT = Path(__file__).parent / "blender_fixtures" / "make_vrm_corpus_bpy.py"

pytestmark = pytest.mark.skipif(not ((BPY_PYTHON or BLENDER) and ADDONS),
                                reason="no pinned Blender/bpy runtime or VRM add-on folder configured")


@pytest.fixture(scope="module")
def runtime(tmp_path_factory) -> si.BlenderRuntime:
    cache = tmp_path_factory.mktemp("runtime")
    if BPY_PYTHON:
        return si.detect_runtime(bpy_python=Path(BPY_PYTHON), cache_root=cache)
    return si.detect_runtime(blender=Path(BLENDER), cache_root=cache)


@pytest.fixture(scope="module")
def corpus(tmp_path_factory, runtime) -> Path:
    out = tmp_path_factory.mktemp("vrm-corpus")
    if runtime.kind == "module":
        argv = [str(runtime.executable), "-I", str(CORPUS_SCRIPT), "--", str(out)]
    else:
        argv = [str(runtime.executable), "--background", "--factory-startup", "--python", str(CORPUS_SCRIPT),
                "--", str(out)]
    done = subprocess.run(argv, timeout=300, capture_output=True, text=True)
    assert (out / "xps_pack.zip").is_file(), done.stdout[-2000:] + done.stderr[-2000:]
    return out


@pytest.fixture()
def kw(tmp_path, runtime) -> dict:
    return dict(runtime=runtime, addons_dir=Path(ADDONS), cache_root=tmp_path / "cache", work_root=tmp_path / "work",
                options=ve.ExportOptions(wall_seconds=240.0, isolation="bwrap" if REQUIRE_BWRAP else "none"))


def vrm_json(path: Path) -> dict:
    """The glTF JSON chunk of a .vrm (GLB) file."""
    data = path.read_bytes()
    assert data[:4] == b"glTF", "not a GLB container"
    length, kind = struct.unpack("<II", data[12:20])
    assert kind == 0x4E4F534A  # "JSON"
    return json.loads(data[20:20 + length])


@pytest.mark.parametrize("asset, method", [
    ("xps_pack.zip", "names"),        # native XPS via the patched fork, texture relinked from textures/
    ("xps_names.fbx", "names"),       # FBX with an embedded 4096 px texture (downscaled to 2048)
    ("valve.blend", "names"),
    ("daz.blend", "names"),
    ("anon.blend", "vrm_addon_structure"),
])
def test_export_ready(corpus, tmp_path, kw, asset, method):
    result = ve.export_asset(corpus / asset, tmp_path / "out", **kw)
    assert result["state"] == "READY", json.dumps(result, indent=2)[:3000]
    assert result["humanoid"]["method"] == method
    assert result["humanoid"]["missing_required"] == []
    assert result["bones"] == 19
    assert result["likeness_authority"] is False
    assert result["cleanup"]["staging_removed"]
    if REQUIRE_BWRAP:
        assert result["isolation"]["mode"] == "bwrap"

    doc = vrm_json(tmp_path / "out" / result["output"])
    vrm = doc["extensions"]["VRMC_vrm"]
    assert {"hips", "spine", "head", "leftUpperArm", "rightLowerLeg"} <= set(vrm["humanoid"]["humanBones"])
    meta = vrm["meta"]
    assert meta["avatarPermission"] == "onlyAuthor" and meta["allowRedistribution"] is False
    assert meta["modification"] == "prohibited" and meta["commercialUsage"] == "personalNonProfit"
    assert len(doc.get("images", [])) >= 1, "textures were dropped"
    assert len(doc.get("skins", [])) == 1


